import { ref } from 'vue'

const STORAGE_KEY = 'pm_locale'
const DEFAULT_LOCALE = 'ja'
const SUPPORTED_LOCALES = ['ja', 'pt', 'th', 'vi', 'id']

const LOCALE_LABELS = {
  ja: '日本語',
  pt: 'Português',
  th: 'ไทย',
  vi: 'Tiếng Việt',
  id: 'Bahasa Indonesia',
}

const LOCALE_CODES = {
  ja: 'ja-JP',
  pt: 'pt-BR',
  th: 'th-TH',
  vi: 'vi-VN',
  id: 'id-ID',
}

const resolveInitialLocale = () => {
  if (typeof window === 'undefined' || !window.localStorage) {
    return DEFAULT_LOCALE
  }
  const stored = window.localStorage.getItem(STORAGE_KEY)
  if (stored && SUPPORTED_LOCALES.includes(stored)) {
    return stored
  }
  return DEFAULT_LOCALE
}

export const locale = ref(resolveInitialLocale())

const formatMessage = (message, params = {}) => {
  if (!params || typeof message !== 'string') return message
  return message.replace(/\{(\w+)\}/g, (_, key) => {
    const value = params[key]
    return value === undefined || value === null ? '' : String(value)
  })
}

export const t = (key, params) => {
  const message =
    MESSAGES[locale.value]?.[key] ||
    MESSAGES[DEFAULT_LOCALE]?.[key] ||
    key
  return formatMessage(message, params)
}

export const setLocale = (nextLocale) => {
  if (!SUPPORTED_LOCALES.includes(nextLocale)) return
  locale.value = nextLocale
  if (typeof window !== 'undefined' && window.localStorage) {
    window.localStorage.setItem(STORAGE_KEY, nextLocale)
  }
}

export const getLocaleOptions = () =>
  SUPPORTED_LOCALES.map((value) => ({
    value,
    label: LOCALE_LABELS[value] || value,
  }))

export const getLocaleCode = () => LOCALE_CODES[locale.value] || LOCALE_CODES[DEFAULT_LOCALE]

if (typeof window !== 'undefined') {
  window.addEventListener('storage', (event) => {
    if (event.key === STORAGE_KEY && event.newValue && SUPPORTED_LOCALES.includes(event.newValue)) {
      locale.value = event.newValue
    }
  })
}

